import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), "utf8");
const sql = read("supabase/member-directory-friends-v1.sql");
const directory = read("src/components/community/MemberPrivacy.js");
assert.match(sql, /directory_listed boolean/);
assert.match(sql, /People lists every eligible member/);
assert.match(sql, /p\.directory_listed/);
assert.match(sql, /from auth\.users u/);
assert.match(sql, /u\.email_confirmed_at is not null/);
assert.match(sql, /mp\.display_name/);
assert.match(sql, /coalesce\(p\.directory_listed, true\)/);
assert.match(sql, /confirmed, non-banned account is an active member/);
assert.match(sql, /left join public\.member_profiles mp/);
assert.match(sql, /'relationship', case when not/);
assert.match(sql, /'private'/);
assert.match(sql, /u\.id = auth\.uid\(\) or public\.qa_privacy_contacts/);
assert.match(sql, /action = 'request'/);
assert.match(directory, /Show my alias in People/);
assert.match(directory, /Add friend/);
assert.match(directory, /Request sent/);
assert.match(directory, /Respond in contacts/);
assert.match(directory, /Friends/);
assert.match(directory, /This member has not opened their profile for contact/);
assert.match(directory, /profile and messages available/);
console.log("Alias-only People directory and friend-request gate wiring passed.");
