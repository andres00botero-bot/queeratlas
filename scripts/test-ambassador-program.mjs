// Run npm run setup:member-privacy-tests once to install the shared test-only
// PGlite runtime. This test always creates a disposable in-memory PostgreSQL DB.
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { randomUUID } from "node:crypto";
import { PGlite } from "../node_modules/.cache/privacy-test-runtime/package/dist/index.js";

const db = new PGlite();
const admin = randomUUID();
const cityEditor = randomUUID();
const venueEditor = randomUUID();
const member = randomUUID();

async function signIn(userId) {
  await db.exec("set role authenticated");
  await db.query("select set_config('request.jwt.claim.sub', $1, false)", [userId]);
}

async function first(sql, parameters = []) {
  return (await db.query(sql, parameters)).rows[0];
}

async function grant(userId, role, city, venueId = null, status = "active", end = null) {
  const row = await first(`
    select public.qa_admin_set_ambassador(
      $1, $2, $3, $4, now() - interval '1 day', $5, $6, 'pilot'
    ) as id
  `, [userId, role, city, venueId, end, status]);
  return row.id;
}

async function save(assignment, entity, id, revision, payload) {
  const row = await first(
    "select public.qa_ambassador_save($1,$2,$3,$4,$5) as saved",
    [assignment, entity, id, revision, JSON.stringify(payload)],
  );
  return row.saved;
}

try {
  await db.exec(`
    create role anon;
    create role authenticated;
    create schema auth;
    create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$
      select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid
    $$;
    grant usage on schema auth to authenticated, anon;
    create table qa_admin_users(user_id uuid primary key);
    create function public.qa_is_admin() returns boolean
      language sql stable security definer set search_path='' as $$
        select exists(select from public.qa_admin_users where user_id=auth.uid())
      $$;
    create table member_profiles(user_id uuid primary key,trusted_contributor boolean default false);
    create table places(venue_intel jsonb,vibe_tags text[],vibe text,
      id bigint generated by default as identity primary key, city text, name text,
      type text, location text, description text, hours text, link text,
      lat double precision, lng double precision, seo_quality_status text
    );
    create table events(event_intel jsonb,vibe_tags text[],vibe text,
      id bigint generated by default as identity primary key, city text, name text,
      location text, description text, date date, start_date date, end_date date,
      hours text, event_status text, link text, ticket_url text, lat double precision, lng double precision
    );
    alter table places enable row level security;
    alter table events enable row level security;
    grant select,insert,update,delete on events,places,member_profiles to authenticated;
    -- Start with broad historical policies to ensure the migration confines writes.
    create policy legacy on places for all to authenticated using(true) with check(true);
    create policy legacy on events for all to authenticated using(true) with check(true);
    insert into places(city,name,type,location) values
      ('copenhagen','Copenhagen club','bar','Street 1'),
      ('sofia','Pilot club','club','Street 2'), ('sofia','Neighbour','club','Street 3');
    insert into events(city,name,date,location) values ('sofia','Existing event','2027-02-01','Street 2');
  `);
  for (const id of [admin, cityEditor, venueEditor, member]) {
    await db.query("insert into auth.users values ($1)", [id]);
  }
  await db.query("insert into qa_admin_users values ($1)", [admin]);
  const migration = await readFile(new URL("../supabase/ambassador-program-v1.sql", import.meta.url), "utf8");
  await db.exec(migration);
  await db.exec(migration);

  await db.exec("create table global_events(vibe_tags text[])");
  await db.exec(await readFile(new URL("../supabase/venue-event-vibe-tags-v2.sql", import.meta.url), "utf8"));

  await signIn(admin);
  const copenhagen = await grant(cityEditor, "city", "copenhagen");
  const sofia = await grant(venueEditor, "venue", "sofia", 2);
  await db.query("select qa_admin_link_ambassador_event(1,2)");
  await assert.rejects(db.query("select qa_admin_link_ambassador_event(1,3)"), /unlinked/);
  await assert.rejects(grant(member, "city", "moscow"), /editorial review/);

  await signIn(member);
  assert.equal((await db.query("select * from qa_ambassador_assignments")).rows.length, 0);
  await assert.rejects(grant(member, "city", "sofia"), { code: "42501" });
  await assert.rejects(db.query("insert into events(city,name) values('sofia','direct')"), { code: "42501" });
  await assert.rejects(db.query("insert into member_profiles values ($1,true)", [member]), { code: "42501" });
  await db.query("insert into member_profiles values ($1,false)", [member]);
  await assert.rejects(db.query("update member_profiles set trusted_contributor=true where user_id=$1", [member]), { code: "42501" });
  await signIn(admin);
  await db.query("update member_profiles set trusted_contributor=true where user_id=$1", [member]);
  await signIn(member);
  await db.query("insert into events(city,name) values('sofia','existing trusted publisher')");
  await signIn(admin);
  await grant(member, "city", "sofia");
  await signIn(member);
  await assert.rejects(db.query("insert into events(city,name) values('sofia','direct')"), { code: "42501" });

  await signIn(cityEditor);
  assert.equal((await db.query("select * from qa_ambassador_assignments")).rows.length, 1);
  const club = await save(copenhagen, "venue", null, null, {
    name: "Pilot venue", type: "bar", location: "Street 4", lat: 55.67, lng: 12.57,
  });
  const draft = {
    name: "Pilot event", location: "Street 4", lat: 55.67, lng: 12.57,
    start_date: "2027-02-01", end_date: "2027-02-02", hours: "21:00–02:00",
    ambassador_venue_id: club.id, request_id: randomUUID(),
  };
  const event = await save(copenhagen, "event", null, null, draft);
  assert.equal(event.city, "copenhagen");
  assert.equal(event.date, draft.start_date);
  assert.equal((await save(copenhagen, "event", null, null, draft)).id, event.id);
  await assert.rejects(save(copenhagen, "event", null, null, { ...draft, name: "Other event" }), /already been used/);
  await assert.rejects(save(copenhagen, "event", null, null, {
    ...draft, request_id: randomUUID(), ambassador_venue_id: 2,
  }), /assigned city/);
  await assert.rejects(save(copenhagen, "venue", 2, 0, { hours: "09:00" }), { code: "42501" });
  await assert.rejects(save(copenhagen, "event", event.id, 0, { city: "sofia" }), /Unsupported/);
  const updated = await save(copenhagen, "event", event.id, 0, { hours: "22:00–03:00", best_arrival: "Before the show" });
  assert.equal(updated.event_intel.best_arrival, "Before the show");
  await assert.rejects(save(copenhagen, "event", event.id, 0, { hours: "23:00" }), { code: "40001" });
  assert.equal((await db.query("select id from qa_ambassador_history")).rows.length, 0);
  assert.equal((await db.query("update events set name='direct' where id=1 returning id")).rows.length, 0);
  assert.equal((await db.query("delete from events where id=1 returning id")).rows.length, 0);

  const annotated = await save(copenhagen, "venue", club.id, 0, { queue_wait: "Short before midnight", vibe_tags: ["techno","social","queer_friendly","sapphic"] });
  assert.deepEqual(annotated.vibe_tags, ["techno","social","queer_friendly","sapphic"]);
  assert.equal(annotated.venue_intel.queue_wait, "Short before midnight");
  assert.equal(annotated.venue_intel.topic_evidence.queue_wait.status, "community_signal");
  await signIn(venueEditor);
  await save(sofia, "event", 1, 1, { event_status: "cancelled" });
  await save(sofia, "venue", 2, 0, { description: "Updated public description" });
  await assert.rejects(save(sofia, "venue", 3, 0, { hours: "09:00" }), { code: "42501" });
  await assert.rejects(save(sofia, "venue", null, null, { name: "Neighbour" }), { code: "42501" });
  await assert.rejects(save(sofia, "event", 1, 2, { ambassador_venue_id: 3 }), /linked venue/);
  await assert.rejects(save(copenhagen, "event", event.id, 1, { hours: "20:00" }), { code: "42501" });

  await signIn(admin);
  const edit = await first("select id from qa_ambassador_history where assignment_id=$1 and entity_type='event' and before_data is not null", [copenhagen]);
  await db.query("select qa_admin_restore_ambassador($1)", [edit.id]);
  assert.equal((await first("select hours from events where id=$1", [event.id])).hours, draft.hours);
  await assert.rejects(db.query("select qa_admin_restore_ambassador($1)", [edit.id]), { code: "40001" });
  await db.query("update places set ambassador_protected=true where id=1");
  await signIn(cityEditor);
  await assert.rejects(save(copenhagen,"venue",1,1,{ name: "Protected" }), { code: "42501" });

  await signIn(admin);
  await grant(cityEditor, "city", "copenhagen", null, "paused");
  await grant(venueEditor, "venue", "sofia", 2, "active", new Date(Date.now() - 60000).toISOString());
  await signIn(cityEditor);
  await assert.rejects(save(copenhagen, "venue", club.id, 0, { hours: "10:00" }), { code: "42501" });
  await signIn(venueEditor);
  await assert.rejects(save(sofia, "event", 1, 2, { hours: "18:00" }), { code: "42501" });
  await db.exec("set role anon");
  assert.equal((await first("select has_function_privilege(current_user,'qa_ambassador_save(uuid,text,bigint,bigint,jsonb)','execute') as allowed")).allowed, false);
  console.log("Ambassador database checks passed: city and venue scope, legacy trust, role expiration, audit, restore, revisions and retries.");
} finally {
  await db.close();
}
