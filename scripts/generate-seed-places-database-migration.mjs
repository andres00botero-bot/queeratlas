import fs from "node:fs";
import path from "node:path";

import { mergeSeedPlaces } from "../src/lib/seedPlacesContent.js";
import { buildPlaceVibeDualWriteFields } from "../src/lib/vibeTaxonomy.js";

const OUTPUT_PATH = path.join(process.cwd(), "supabase", "seed-places-to-database-v3.sql");
const SQL_JSON_DELIMITER = "$qa_seed_places$";

function normalizeSeedPlace(place = {}) {
  const vibeFields = buildPlaceVibeDualWriteFields({
    type: String(place.type || "bar"),
    vibe: String(place.vibe || ""),
  });
  return {
    legacy_seed_id: String(place.id || "").trim(),
    city: String(place.city || "").trim(),
    name: String(place.name || "").trim(),
    type: String(place.type || "bar").trim(),
    description: String(place.description || "").trim(),
    vibe: String(place.vibe || "").trim(),
    vibe_tags: vibeFields.vibe_tags,
    hours: String(place.hours || "").trim(),
    link: String(place.link || "").trim(),
    location: String(place.location || "").trim(),
    lat: Number(place.lat),
    lng: Number(place.lng),
    venue_intel:
      place?.venue_intel && typeof place.venue_intel === "object" ? place.venue_intel : {},
  };
}

const seedPlaces = mergeSeedPlaces([]).map(normalizeSeedPlace);
const invalidPlace = seedPlaces.find(
  (place) =>
    !place.legacy_seed_id ||
    !place.city ||
    !place.name ||
    !place.type ||
    !Number.isFinite(place.lat) ||
    !Number.isFinite(place.lng),
);

if (invalidPlace) {
  throw new Error(`Invalid seed place: ${JSON.stringify(invalidPlace)}`);
}

if (new Set(seedPlaces.map((place) => place.legacy_seed_id)).size !== seedPlaces.length) {
  throw new Error("Seed place IDs must be unique before generating the migration.");
}

const jsonPayload = JSON.stringify(seedPlaces);
if (jsonPayload.includes(SQL_JSON_DELIMITER)) {
  throw new Error(`Seed payload contains reserved SQL delimiter ${SQL_JSON_DELIMITER}.`);
}

const sql = `-- Queer Atlas: move every runtime seed venue into public.places.
-- Generated by scripts/generate-seed-places-database-migration.mjs.
-- Revision: v3-single-block. Do not run the older v1 or v2 files.
-- Existing database rows win: matching city/name rows are linked, never overwritten.
-- Safe to run repeatedly.

alter table if exists public.places
  add column if not exists legacy_seed_id text;

create unique index if not exists places_legacy_seed_id_unique
  on public.places (legacy_seed_id)
  where legacy_seed_id is not null;

-- The service tag belongs to public.services, never to a venue in public.places.
update public.places
set vibe_tags = array_remove(vibe_tags, 'service')
where 'service' = any(vibe_tags);

alter table public.places
  drop constraint if exists qa_places_vibe_tags_allowed;

alter table public.places
  add constraint qa_places_vibe_tags_allowed
  check (
    (type = 'store' and vibe_tags = array['store']::text[])
    or (
      type <> 'store'
      and vibe_tags <@ array[
        'techno',
        'pop',
        'mixed',
        'electronic',
        'men_only',
        'after',
        'chill',
        'cultural',
        'fetish',
        'social',
        'cozy',
        'massive',
        'luxury',
        'festival',
        'underground',
        'cruise',
        'relax',
        'drag',
        'industrial'
      ]::text[]
    )
  );

-- The payload and every database operation live inside this single statement.
-- No temporary or persistent staging relation is required by this revision.
do $qa_import_places$
declare
  seed_payload constant jsonb := ${SQL_JSON_DELIMITER}${jsonPayload}${SQL_JSON_DELIMITER}::jsonb;
  seed_record record;
  candidate_id bigint;
begin
  for seed_record in
    select *
    from jsonb_to_recordset(seed_payload) as x(
      legacy_seed_id text,
      city text,
      name text,
      type text,
      description text,
      vibe text,
      vibe_tags jsonb,
      hours text,
      link text,
      location text,
      lat double precision,
      lng double precision,
      venue_intel jsonb
    )
    order by legacy_seed_id
  loop
    if exists (
      select 1
      from public.places already_linked
      where already_linked.legacy_seed_id = seed_record.legacy_seed_id
    ) then
      continue;
    end if;

    select min(match_row.id)
    into candidate_id
    from public.places match_row
    where match_row.legacy_seed_id is null
      and lower(btrim(match_row.city)) = lower(btrim(seed_record.city))
      and lower(btrim(match_row.name)) = lower(btrim(seed_record.name));

    if candidate_id is not null then
      begin
        update public.places candidate
        set legacy_seed_id = seed_record.legacy_seed_id
        where candidate.id = candidate_id
          and candidate.legacy_seed_id is null
          and not exists (
            select 1
            from public.places already_linked
            where already_linked.legacy_seed_id = seed_record.legacy_seed_id
          );
      exception
        when unique_violation then
          null;
      end;
    end if;

    if not exists (
      select 1
      from public.places existing
      where existing.legacy_seed_id = seed_record.legacy_seed_id
         or (
           lower(btrim(existing.city)) = lower(btrim(seed_record.city))
           and lower(btrim(existing.name)) = lower(btrim(seed_record.name))
         )
    ) then
      begin
        insert into public.places (
          legacy_seed_id,
          city,
          name,
          type,
          description,
          vibe,
          vibe_tags,
          legacy_vibe_user_set,
          hours,
          link,
          location,
          lat,
          lng,
          venue_intel
        ) values (
          seed_record.legacy_seed_id,
          seed_record.city,
          seed_record.name,
          seed_record.type,
          seed_record.description,
          seed_record.vibe,
          array(select jsonb_array_elements_text(coalesce(seed_record.vibe_tags, '[]'::jsonb))),
          false,
          seed_record.hours,
          nullif(seed_record.link, ''),
          nullif(seed_record.location, ''),
          seed_record.lat,
          seed_record.lng,
          coalesce(seed_record.venue_intel, '{}'::jsonb)
        )
        on conflict do nothing;
      exception
        when unique_violation then
          null;
      end;
    end if;
  end loop;
end
$qa_import_places$;

comment on column public.places.legacy_seed_id is
  'Legacy static seed identifier retained only for backwards-compatible placeId URLs.';

`;

fs.writeFileSync(OUTPUT_PATH, sql, "utf8");
console.log(`Generated ${OUTPUT_PATH} with ${seedPlaces.length} venues.`);
