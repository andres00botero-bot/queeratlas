-- QARI 2.0 · parallel non-compensatory profile schema.
-- Do not run until the first reviewed QARI 2.0 country profiles are ready to publish.

begin;

create table if not exists public.qa_qari_v2_profiles (
  destination_key text primary key,
  country text not null,
  public_level text not null check (public_level in ('lower', 'moderate', 'high', 'extreme')),
  legal_level text not null check (legal_level in ('lower', 'moderate', 'high', 'extreme')),
  state_repression_level text not null check (state_repression_level in ('lower', 'moderate', 'high', 'extreme')),
  digital_exposure_level text not null check (digital_exposure_level in ('lower', 'moderate', 'high', 'extreme')),
  social_civil_level text not null check (social_civil_level in ('lower', 'moderate', 'high', 'extreme')),
  legal_evidence_availability text not null check (legal_evidence_availability in ('good', 'limited', 'opaque', 'unknown')),
  state_repression_evidence_availability text not null check (state_repression_evidence_availability in ('good', 'limited', 'opaque', 'unknown')),
  digital_exposure_evidence_availability text not null check (digital_exposure_evidence_availability in ('good', 'limited', 'opaque', 'unknown')),
  social_civil_evidence_availability text not null check (social_civil_evidence_availability in ('good', 'limited', 'opaque', 'unknown')),
  trend text not null check (trend in ('improving', 'stable', 'deteriorating', 'insufficient_new_evidence')),
  summary text not null check (char_length(btrim(summary)) >= 40),
  methodology_version text not null default '2.0-2026',
  reviewed_at date not null,
  next_review_at date not null,
  is_published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.qa_qari_v2_findings (
  id bigint generated by default as identity primary key,
  destination_key text not null references public.qa_qari_v2_profiles(destination_key) on delete cascade,
  dimension text not null check (dimension in ('legal', 'state_repression', 'digital_exposure', 'social_civil')),
  rule_code text not null,
  evidence_grade text not null check (evidence_grade in ('A', 'B', 'C')),
  primary_scoring_owner boolean not null default true,
  source_label text not null,
  source_url text not null check (source_url ~ '^https://'),
  event_date date,
  checked_at date not null,
  review_due_at date not null,
  status text not null default 'active' check (status in ('active', 'monitoring', 'superseded', 'resolved')),
  supports_claim text not null check (char_length(btrim(supports_claim)) >= 20),
  created_at timestamptz not null default now()
);

create index if not exists qa_qari_v2_profiles_next_review_idx
  on public.qa_qari_v2_profiles (next_review_at)
  where is_published = true;
create index if not exists qa_qari_v2_findings_destination_idx
  on public.qa_qari_v2_findings (destination_key, dimension, status);

create or replace function public.qa_qari_v2_touch_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists qa_qari_v2_profiles_touch_updated_at on public.qa_qari_v2_profiles;
create trigger qa_qari_v2_profiles_touch_updated_at
before update on public.qa_qari_v2_profiles
for each row execute function public.qa_qari_v2_touch_updated_at();

alter table public.qa_qari_v2_profiles enable row level security;
alter table public.qa_qari_v2_findings enable row level security;

drop policy if exists qa_qari_v2_profiles_public_read on public.qa_qari_v2_profiles;
create policy qa_qari_v2_profiles_public_read
on public.qa_qari_v2_profiles
for select
to anon, authenticated
using (is_published = true);

drop policy if exists qa_qari_v2_findings_public_read on public.qa_qari_v2_findings;
create policy qa_qari_v2_findings_public_read
on public.qa_qari_v2_findings
for select
to anon, authenticated
using (
  exists (
    select 1 from public.qa_qari_v2_profiles profile
    where profile.destination_key = qa_qari_v2_findings.destination_key
      and profile.is_published = true
  )
);

grant select on public.qa_qari_v2_profiles, public.qa_qari_v2_findings to anon, authenticated;

commit;
