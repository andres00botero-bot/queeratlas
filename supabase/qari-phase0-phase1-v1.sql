-- Reviewed pilot data and compact /cities read model.
-- Safe to run more than once in Supabase SQL Editor.

begin;

create table if not exists public.qa_qari_profiles (
  destination_key text primary key,
  scope_type text not null check (scope_type in ('country', 'city')),
  country text not null,
  city_key text,
  legal_risk smallint not null check (legal_risk between 0 and 100),
  social_risk smallint not null check (social_risk between 0 and 100),
  digital_risk smallint not null check (digital_risk between 0 and 100),
  risk_floor smallint not null default 0 check (risk_floor between 0 and 100),
  qari_score smallint generated always as (
    greatest(
      round((legal_risk * 0.35) + (social_risk * 0.40) + (digital_risk * 0.25)),
      risk_floor
    )::smallint
  ) stored,
  confidence text not null check (confidence in ('low', 'medium', 'high')),
  summary text not null check (char_length(btrim(summary)) >= 40),
  methodology_version text not null default '1.0',
  reviewed_by text not null default 'Queer Atlas editorial desk',
  reviewed_at date not null,
  is_published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    (scope_type = 'country' and city_key is null)
    or
    (scope_type = 'city' and nullif(btrim(city_key), '') is not null)
  )
);

create index if not exists qa_qari_profiles_country_idx
  on public.qa_qari_profiles (lower(country));

create index if not exists qa_qari_profiles_city_idx
  on public.qa_qari_profiles (city_key)
  where city_key is not null;

create table if not exists public.qa_qari_sources (
  id bigint generated by default as identity primary key,
  destination_key text not null references public.qa_qari_profiles(destination_key) on delete cascade,
  axis text not null check (axis in ('legal', 'social', 'digital', 'methodology')),
  source_type text not null check (source_type in ('legal_database', 'government', 'ngo_report', 'official_statistics', 'methodology')),
  label text not null,
  url text not null check (url ~ '^https://'),
  supports_claim text not null check (char_length(btrim(supports_claim)) >= 20),
  published_at date,
  checked_at date not null,
  created_at timestamptz not null default now(),
  unique (destination_key, axis, url)
);

create or replace function public.qa_qari_touch_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists qa_qari_profiles_touch_updated_at on public.qa_qari_profiles;
create trigger qa_qari_profiles_touch_updated_at
before update on public.qa_qari_profiles
for each row execute function public.qa_qari_touch_updated_at();

alter table public.qa_qari_profiles enable row level security;
alter table public.qa_qari_sources enable row level security;

drop policy if exists qa_qari_profiles_public_read on public.qa_qari_profiles;
create policy qa_qari_profiles_public_read
on public.qa_qari_profiles
for select
to anon, authenticated
using (is_published = true);

drop policy if exists qa_qari_sources_public_read on public.qa_qari_sources;
create policy qa_qari_sources_public_read
on public.qa_qari_sources
for select
to anon, authenticated
using (
  exists (
    select 1
    from public.qa_qari_profiles profile
    where profile.destination_key = qa_qari_sources.destination_key
      and profile.is_published = true
  )
);

grant select on public.qa_qari_profiles to anon, authenticated;
grant select on public.qa_qari_sources to anon, authenticated;

