-- QueerAtlas Google Search Console connection and read-only SEO inventory.
-- Run once in the Supabase SQL editor before connecting Google.

create table if not exists public.qa_gsc_connections (
  id uuid primary key default gen_random_uuid(),
  site_url text not null unique,
  refresh_token_ciphertext text not null,
  granted_scope text not null default '',
  token_type text not null default 'Bearer',
  connected_by uuid references auth.users(id) on delete set null,
  connected_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_synced_at timestamptz,
  last_error text not null default '',
  last_summary jsonb not null default '{}'::jsonb
);

create table if not exists public.qa_gsc_search_performance (
  id bigint generated by default as identity primary key,
  site_url text not null,
  period_start date not null,
  period_end date not null,
  source_type text not null check (source_type in ('page', 'query_page')),
  query text not null default '',
  page text not null default '',
  country text not null default '',
  device text not null default '',
  clicks double precision not null default 0,
  impressions double precision not null default 0,
  ctr double precision not null default 0,
  position double precision not null default 0,
  synced_at timestamptz not null default now(),
  unique (site_url, period_start, period_end, source_type, query, page, country, device)
);

create index if not exists qa_gsc_performance_period_idx
  on public.qa_gsc_search_performance (period_end desc, impressions desc);
create index if not exists qa_gsc_performance_page_idx
  on public.qa_gsc_search_performance (page);

create table if not exists public.qa_gsc_sitemaps (
  site_url text not null,
  path text not null,
  last_submitted timestamptz,
  last_downloaded timestamptz,
  is_pending boolean not null default false,
  is_sitemaps_index boolean not null default false,
  warnings bigint not null default 0,
  errors bigint not null default 0,
  contents jsonb not null default '[]'::jsonb,
  synced_at timestamptz not null default now(),
  primary key (site_url, path)
);

create table if not exists public.qa_gsc_url_inspections (
  url text primary key,
  site_url text not null,
  verdict text not null default '',
  coverage_state text not null default '',
  robots_txt_state text not null default '',
  indexing_state text not null default '',
  page_fetch_state text not null default '',
  google_canonical text not null default '',
  user_canonical text not null default '',
  crawled_as text not null default '',
  last_crawl_time timestamptz,
  referring_urls jsonb not null default '[]'::jsonb,
  sitemaps jsonb not null default '[]'::jsonb,
  inspected_at timestamptz not null default now()
);

create index if not exists qa_gsc_inspections_status_idx
  on public.qa_gsc_url_inspections (verdict, coverage_state);
create index if not exists qa_gsc_inspections_oldest_idx
  on public.qa_gsc_url_inspections (inspected_at asc);

alter table public.qa_gsc_connections enable row level security;
alter table public.qa_gsc_search_performance enable row level security;
alter table public.qa_gsc_sitemaps enable row level security;
alter table public.qa_gsc_url_inspections enable row level security;

drop policy if exists qa_gsc_connections_select_admin on public.qa_gsc_connections;
create policy qa_gsc_connections_select_admin on public.qa_gsc_connections
for select to authenticated using (public.qa_is_admin());

drop policy if exists qa_gsc_performance_select_admin on public.qa_gsc_search_performance;
create policy qa_gsc_performance_select_admin on public.qa_gsc_search_performance
for select to authenticated using (public.qa_is_admin());

drop policy if exists qa_gsc_sitemaps_select_admin on public.qa_gsc_sitemaps;
create policy qa_gsc_sitemaps_select_admin on public.qa_gsc_sitemaps
for select to authenticated using (public.qa_is_admin());

drop policy if exists qa_gsc_inspections_select_admin on public.qa_gsc_url_inspections;
create policy qa_gsc_inspections_select_admin on public.qa_gsc_url_inspections
for select to authenticated using (public.qa_is_admin());

revoke all on table public.qa_gsc_connections from anon;
revoke all on table public.qa_gsc_search_performance from anon;
revoke all on table public.qa_gsc_sitemaps from anon;
revoke all on table public.qa_gsc_url_inspections from anon;
revoke insert, update, delete on table public.qa_gsc_connections from authenticated;
revoke insert, update, delete on table public.qa_gsc_search_performance from authenticated;
revoke insert, update, delete on table public.qa_gsc_sitemaps from authenticated;
revoke insert, update, delete on table public.qa_gsc_url_inspections from authenticated;
grant select on table public.qa_gsc_connections to authenticated;
grant select on table public.qa_gsc_search_performance to authenticated;
grant select on table public.qa_gsc_sitemaps to authenticated;
grant select on table public.qa_gsc_url_inspections to authenticated;
grant all on table public.qa_gsc_connections to service_role;
grant all on table public.qa_gsc_search_performance to service_role;
grant all on table public.qa_gsc_sitemaps to service_role;
grant all on table public.qa_gsc_url_inspections to service_role;
